"""Slim-schema experiment: structurally remove pass narratives and pass rule quotes, compare reasoning.

The slim schema is generated by the same output_spec mechanism from static dataclasses below
(experiment only; project code untouched). The recorded system prompt's schema block is swapped
verbatim; everything else in the request is identical.
usage: python slim_schema.py <trace2.json> <case-substring> [repeats]
"""
import concurrent.futures as cf, json, sys, time, urllib.request
from dataclasses import dataclass, field
from pathlib import Path
from typing import Literal, Optional, Union
OUT = Path(__file__).resolve().parent
ROOT = OUT.parents[2]
sys.path.insert(0, str(ROOT))
from impl.core.llm_client import extract_json
from impl.core.structured_output import StructuredOutputSpec, render_output_constraint, validate_output
from impl.projects.llm_probe.eval_axes.adapters import process_output as po

CRIT = {'pattern': r'^C[0-9]+$', 'description': '程序列出的判准短编号，只写编号如 C1，不带冒号和说明'}


@dataclass
class PassCheck:
    criterion: str = field(metadata=CRIT)
    outcome: Literal['pass'] = field(metadata={'description': '做到'})
    evidence: list[str] = field(metadata={'nonempty': True, 'description': '支撑通过的记录编号。' + po._EVIDENCE_IDS})


@dataclass
class OtherCheck:
    criterion: str = field(metadata=CRIT)
    outcome: Literal['fail', 'not_applicable'] = field(metadata={'description': '有效输入下没做到 / 有正面依据本次不需要'})
    fact: str = field(metadata={'nonempty': True})
    missing: list[str] = field(default_factory=list)


@dataclass
class SlimRule:
    quotes: list[po.Quote] = field(metadata={'nonempty': True})
    applicability: str = field(metadata={'nonempty': True, 'description': '为何是规则、如何适用于本单位'})
    fact: str = field(metadata={'nonempty': True})
    outcome: Literal['fail', 'not_applicable'] = 'fail'
    missing: list[str] = field(default_factory=list)


@dataclass
class SlimUnit:
    unit: str = field(metadata={'pattern': r'^U[0-9]+$', 'description': '程序列出的单位短编号，如 U1'})
    checks: list[Union[PassCheck, OtherCheck, po.GapCheck, po.InvalidCheck]] = field(metadata={'description': '恰好覆盖该单位 criteria 里列出的每个 C；单位的 criteria 为空时必须是空数组，不要自己编判准。'})
    rules: list[Union[SlimRule, po.GapRule, po.InvalidRule]] = field(default_factory=list, metadata={'description': '只在用设计规则判出不通过时填写；通过不引规则。按顺序称 D1/D2。'})
    missing_criterion: list[str] = field(default_factory=list, metadata={'description': '没有程序判准且没有引用设计规则时必填：缺什么判准。'})
    necessity: Optional[po.Necessity] = field(default=None, metadata={'description': '单位带 action 时必填；单位没有 action 时不要填。'})
    matched: str = field(default='', metadata={'allow_empty': True, 'description': '应发生单位对接的实际行使环节（从 candidates 中选），没找到留空。'})


@dataclass
class SlimAxis:
    reason: str = field(metadata={'description': '一两句话，不引用原文。'})
    scope_note: str = field(metadata={'description': '本批判定范围和不可见部分，一两句话，不引用原文。'})
    units: list[SlimUnit]
    problems: list[po.ProblemRecord] = field(default_factory=list, metadata={'description': '每个独立问题一条。'})


SLIM = StructuredOutputSpec.from_dataclass(SlimAxis, required_nonempty=['reason', 'scope_note'])
OLD_BLOCK, NEW_BLOCK = render_output_constraint(po.OUTPUT), render_output_constraint(SLIM)

env = dict(l.rstrip('\n').split('=', 1) for l in open(ROOT / '.runtime/instances/inst-16fa340ac786414f/tracing/.env.verifier_primary') if '=' in l and not l.startswith('#'))
BASE, KEY = env['UPSTREAM_API_BASE'].strip('"'), env['UPSTREAM_API_KEY'].strip('"')
AXES = ('tool_execution', 'model_capability', 'context_memory')

def call(label, body, spec):
    body = dict(body, stream=True, stream_options={'include_usage': True})
    req = urllib.request.Request(BASE + '/chat/completions', data=json.dumps(body).encode(), headers={'Authorization': 'Bearer ' + KEY, 'Content-Type': 'application/json'})
    t = time.time(); usage = {}; content = []
    try:
        with urllib.request.urlopen(req, timeout=1200) as r:
            for raw in r:
                l = raw.decode('utf-8', 'ignore').strip()
                if not l.startswith('data:') or l == 'data: [DONE]': continue
                try: j = json.loads(l[5:])
                except Exception: continue
                if j.get('usage'): usage = j['usage']
                for ch in j.get('choices') or []:
                    if (ch.get('delta') or {}).get('content'): content.append(ch['delta']['content'])
    except Exception as e:
        return dict(label=label, error=f'{type(e).__name__}: {str(e)[:120]}', elapsed=round(time.time() - t))
    text = ''.join(content)
    res = dict(label=label, elapsed=round(time.time() - t), reasoning=(usage.get('completion_tokens_details') or {}).get('reasoning_tokens'),
               completion=usage.get('completion_tokens'), chars=len(text), text=text)
    try:
        o = extract_json(text); res['schema_errors'] = validate_output(o, spec)[:2]
        res['outcomes'] = {f"{u['unit']}/{c['criterion']}": c['outcome'] for u in o.get('units', []) for c in u.get('checks', [])}
        res['problems'] = len(o.get('problems', []))
    except Exception as e:
        res['schema_errors'] = [f'parse: {type(e).__name__}']
    return res

if __name__ == '__main__':
    print(f'schema block: 原 {len(OLD_BLOCK)} 字符 → 精简 {len(NEW_BLOCK)} 字符', flush=True)
    trace = json.load(open(sys.argv[1])); reps = int(sys.argv[3]) if len(sys.argv) > 3 else 3
    case = next(c for c in trace['cases'] if sys.argv[2] in c['identity']['case_id'])
    jobs = []
    for x in case['calls']:
        st = (x.get('raw_request') or {}).get('stage') or ''
        axis = next((a for a in AXES if st.startswith('llm_probe_process_' + a)), None)
        if not axis: continue
        base = x['raw_request']['client_request']
        slim = json.loads(json.dumps(base)); sm = slim['messages'][0]
        assert sm['role'] == 'system' and OLD_BLOCK in sm['content']
        sm['content'] = sm['content'].replace(OLD_BLOCK, NEW_BLOCK)
        for i in range(reps):
            jobs += [(f'{axis}|原样|{i}', base, po.OUTPUT), (f'{axis}|精简结构|{i}', slim, SLIM)]
    res = []
    with cf.ThreadPoolExecutor(len(jobs)) as ex:
        for r in ex.map(lambda j: call(*j), jobs):
            res.append(r); print(json.dumps({k: v for k, v in r.items() if k not in ('outcomes', 'text')}, ensure_ascii=False), flush=True)
    (OUT / 'slim_schema_results.json').write_text(json.dumps(res, ensure_ascii=False, indent=1))
